#!/usr/bin/env python3
"""Generate internal typed adapters and four family exports from HS signatures.

abi.def is append-only within each section. Section tags and operation indices
are stable within the private v3 ABI; new sections must be appended to a family.
Generated adapters have internal linkage, not legacy public C ABI symbols.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
FAMILIES = {
    "node": ("configuration", "script_policy"),
    "parent": ("parent_replay",),
    "bmm": ("bmm", "bmm_proof", "bmm_codec", "bmm_state"),
    "peg": ("deposit", "deposit_state", "deposit_evidence", "withdrawal"),
}


def generate():
    source = (ROOT / "Drivechain.hs").read_text()
    signatures = dict(re.findall(r"^(elements_hs_\w+)\s*::\s*([^\n]*(?:\n  ->[^\n]*)*)", source, re.M))
    domains = {}
    names = set()
    for line in (ROOT / "abi.def").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        domain, symbol, function = line.split()
        if symbol in names:
            raise ValueError(f"duplicate ABI symbol: {symbol}")
        names.add(symbol)
        types = [t.strip() for t in signatures[function].split("->")]
        if types[-1] not in ("IO Int32", "IO Int64"):
            raise ValueError(f"unsupported ABI return: {types[-1]}")
        domains.setdefault(domain, []).append((symbol, function, types))
    hs = ['{-# LANGUAGE ForeignFunctionInterface #-}', '-- Generated by generate_abi.py; edit abi.def and Drivechain.hs.',
          'module DomainABI where', 'import Abi (Entry, dispatchFamily, handler)', 'import qualified Drivechain as D', '']
    cpp = ['// Generated by generate_abi.py. Internal adapters, not public exports.', '#pragma once',
           '#include <DomainABI_stub.h>', '#include <haskell/abi.h>',
           '#include <array>', '#include <span>', '#include <utility>', '']
    numbers = {'Word8': 'uint8_t', 'Word32': 'uint32_t', 'Word64': 'uint64_t', 'Int32': 'int32_t', 'Int64': 'int64_t'}

    def ctype(t):
        if t in numbers:
            return numbers[t]
        if t.startswith('FunPtr '):
            return 'HsFunPtr'
        if t.startswith('Ptr '):
            inner = t[4:]
            if inner == '()':
                return 'void*'
            if inner == 'Double':
                return 'double*'
            return ctype(inner.strip('()')) + '*'
        if t == 'Word16':
            return 'uint16_t'
        raise ValueError(f'unsupported ABI argument: {t}')

    sections = [section for family in FAMILIES.values() for section in family]
    if len(sections) != len(set(sections)) or set(sections) != domains.keys():
        raise ValueError("ABI families must cover every section exactly once")
    for family, sections in FAMILIES.items():
        export = f'elements_hs_{family}_api_v3'
        hs += [f'foreign export ccall "{export}" {family} :: Entry',
               f'{family} :: Entry', f'{family} = dispatchFamily']
        counts = ', '.join(str(len(domains[section])) for section in sections)
        cpp += [f'static constexpr uint32_t elements_hs_{family}_sections_v3[]{{{counts}}};']
        for tag, section in enumerate(sections):
            rows = domains[section]
            if tag >= 65536 or len(rows) > 65536:
                raise ValueError("ABI section or operation exceeds 16-bit index")
            hs += [f'  {"[" if tag == 0 else ","} -- {section}: section {tag}',
                   '    [ ' + '\n    , '.join(f'handler D.{function}' for _, function, _ in rows) + '\n    ]']
            cpp += [f'// {section}: section {tag}']
            for opcode, (symbol, _, types) in enumerate(rows):
                ret = numbers[types[-1][3:]]
                signature = f'{ret}(' + ', '.join(ctype(t) for t in types[:-1]) + ')'
                cpp += [f'static constexpr elements_abi::Binding<{export}, {(tag << 16) | opcode}, {signature}> {symbol}{{}};']
        hs += ['  ]', '']
    cpp += ['static constexpr std::array elements_hs_families_v3{',
            ',\n'.join(f'    std::pair{{&elements_hs_{family}_api_v3, std::span<const uint32_t>{{elements_hs_{family}_sections_v3}}}}' for family in FAMILIES), '};']
    return {'DomainABI.hs': '\n'.join(hs), 'domain_abi.h': '\n'.join(cpp)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{path}: regenerate with generate_abi.py')
        else:
            path.write_text(content)
