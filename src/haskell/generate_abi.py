#!/usr/bin/env python3
"""Generate internal typed adapters and domain exports from ordinary HS signatures.

abi.def is append-only within each domain: row order is the v1 operation number.
Generated adapters have internal linkage, not legacy public C ABI symbols.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def generate():
    source = (ROOT / "Drivechain.hs").read_text()
    signatures = dict(re.findall(r"^(elements_hs_\w+)\s*::\s*([^\n]*(?:\n  ->[^\n]*)*)", source, re.M))
    domains = {}
    names = set()
    for line in (ROOT / "abi.def").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        domain, symbol, function = line.split()
        if symbol in names:
            raise ValueError(f"duplicate ABI symbol: {symbol}")
        names.add(symbol)
        types = [t.strip() for t in signatures[function].split("->")]
        if types[-1] not in ("IO Int32", "IO Int64"):
            raise ValueError(f"unsupported ABI return: {types[-1]}")
        domains.setdefault(domain, []).append((symbol, function, types))
    hs = ['{-# LANGUAGE ForeignFunctionInterface #-}', '-- Generated by generate_abi.py; edit abi.def and Drivechain.hs.',
          'module DomainABI where', 'import Abi (dispatch, handler)', 'import qualified Drivechain as D',
          'import Data.Int (Int32)', 'import Data.Word (Word32, Word64)', 'import Foreign.Ptr (Ptr, FunPtr)', '']
    cpp = ['// Generated by generate_abi.py. Internal adapters, not public exports.', '#pragma once',
           '#include <DomainABI_stub.h>', '#include <Drivechain_stub.h>', '#include <haskell/abi.h>',
           '#include <array>', '#include <utility>', '']
    abi_type = 'Word32 -> Word32 -> Ptr Word64 -> Word32 -> Ptr (Ptr ()) -> Word32 -> Ptr (FunPtr ()) -> Ptr Word64 -> IO Int32'
    numbers = {'Word8': 'uint8_t', 'Word32': 'uint32_t', 'Word64': 'uint64_t', 'Int32': 'int32_t', 'Int64': 'int64_t'}

    def ctype(t):
        if t in numbers:
            return numbers[t]
        if t.startswith('FunPtr '):
            return 'HsFunPtr'
        if t.startswith('Ptr '):
            inner = t[4:]
            if inner == '()':
                return 'void*'
            if inner == 'Double':
                return 'double*'
            return ctype(inner.strip('()')) + '*'
        if t == 'Word16':
            return 'uint16_t'
        raise ValueError(f'unsupported ABI argument: {t}')

    for domain, rows in domains.items():
        export = f'elements_hs_{domain}_api_v1'
        cpp += [f'static constexpr uint32_t elements_hs_{domain}_operation_count_v1{{{len(rows)}}};']
        hs += [f'foreign export ccall "{export}" {domain} :: {abi_type}',
               f'{domain} :: {abi_type}', f'{domain} = dispatch',
               '  [ ' + '\n  , '.join(f'handler D.{function}' for _, function, _ in rows) + '\n  ]', '']
        for opcode, (symbol, _, types) in enumerate(rows):
            args = types[:-1]
            ret = numbers[types[-1][3:]]
            signature = f'{ret}(' + ', '.join(ctype(t) for t in args) + ')'
            cpp += [f'static constexpr elements_abi::Binding<{export}, {opcode}, {signature}> {symbol}{{}};']
    cpp += ['static constexpr std::array elements_hs_domains_v1{',
            ',\n'.join(f'    std::pair{{&elements_hs_{domain}_api_v1, elements_hs_{domain}_operation_count_v1}}' for domain in domains), '};']
    return {'DomainABI.hs': '\n'.join(hs), 'domain_abi.h': '\n'.join(cpp)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{path}: regenerate with generate_abi.py')
        else:
            path.write_text(content)
