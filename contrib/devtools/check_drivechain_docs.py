#!/usr/bin/env python3
"""Generate and check operator identity documentation without changing consensus."""

import argparse
from pathlib import Path

from elements_identity_refreeze import Header, IDENTITY_HEADER, ROOT


def identity_document():
    header = Header(IDENTITY_HEADER)
    fields = (
        ("Chain", "NETWORK_ID", "string"),
        ("Slot", "SIDECHAIN_SLOT", "integer"),
        ("Chain data subdirectory", "DATA_DIR", "string"),
        ("Elements RPC port", "RPC_PORT", "integer"),
        ("Elements P2P port", "P2P_PORT", "integer"),
        ("Parent RPC port", "MAINCHAIN_RPC_PORT", "integer"),
        ("Parent checkpoint height", "PARENT_CHECKPOINT_HEIGHT", "integer"),
        ("Parent checkpoint hash", "PARENT_CHECKPOINT_HASH", "string"),
        ("Parent genesis (shared ancestry, not fork identification)", "PARENT_GENESIS", "string"),
        ("Elements genesis", "GENESIS_HASH", "string"),
        ("Pegged asset", "PEGGED_ASSET", "string"),
        ("Required fresh parent proposal hash", "PROPOSAL_HASH", "string"),
        ("Canonical address HRP", "BECH32_HRP", "string"),
        ("Canonical confidential address HRP", "BLECH32_HRP", "string"),
    )
    rows = [f"| {label} | `{getattr(header, kind)(name)}` |" for label, name, kind in fields]
    return "\n".join([
        "# Built-In Drivechain Identity", "",
        "Generated by `contrib/devtools/check_drivechain_docs.py --write` from",
        "`src/elements_drivechain_identity.h`; do not hand-edit the table.", "",
        "This is the production identity for the Elements mainnet deployment.",
        "It requires a new matching parent proposal; no activation is implied.", "",
        "| Property | Frozen value |", "| --- | --- |", *rows, "",
        "Verify the parent fork and authenticated proposal activation before funding.",
        "Matching genesis or address prefixes alone does not identify the parent fork.",
        "Never reuse another network's chain, index or wallet databases.", "",
        "The native mainnet deposit rule requires six parent confirmations. The",
        "identity's historical `PEGIN_MIN_DEPTH=100` is retained in its commitment;",
        "it is not the effective native deposit depth. See `GetDrivechainPeginConfirmationDepth`",
        "and the deposit-depth tests, not a constant in isolation.", "",
    ])


def check_operator_docs():
    stale = ("18302", "995347", "elements-v11", "elements-betanet-v1", "elements-betanet-slot24-v1", "slot 130", "slot-130")
    errors = []
    for name in ("README.md", "doc/drivechain-rpc-security.md", "doc/drivechain-peg-operations.md"):
        text = (ROOT / name).read_text()
        for value in stale:
            if value in text:
                errors.append(f"{name}: stale operator identity {value!r}")
        if "drivechain-network-identity.md" not in text:
            errors.append(f"{name}: missing generated identity reference")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    path = ROOT / "doc/drivechain-network-identity.md"
    expected = identity_document()
    if args.write:
        path.write_text(expected)
    errors = check_operator_docs()
    if not path.exists() or path.read_text() != expected:
        errors.append("Generated identity documentation differs from the source header; run --write")
    if errors:
        parser.exit(1, "\n".join(errors) + "\n")
    print("Drivechain operator identity documentation matches the source header")


if __name__ == "__main__":
    main()
